class GameParser:
    """Parses game output and updates state."""
    
    # Login flow patterns
    PATTERNS = {
        'username_prompt': re.compile(r'(?:enter your username|username.*?:)', re.I),
        'password_prompt': re.compile(r'(?:enter your password|password:)', re.I),
        'kick_prompt': re.compile(r'(?:already (?:logged in|connected)|kick them)', re.I),
        'new_password': re.compile(r'(?:create a new password|new password)', re.I),
        'confirm_password': re.compile(r'confirm password', re.I),
        'character_name': re.compile(r'(?:enter a name|character name|name for your)', re.I),
        'choose_race': re.compile(r'(?:choose.*race|select.*race|pick.*race)', re.I),
        'choose_class': re.compile(r'(?:choose.*class|select.*class|pick.*class)', re.I),
        'press_enter': re.compile(r'press.*enter', re.I),
        'welcome': re.compile(r'(?:welcome back|you have entered|entering the world)', re.I),
        'game_prompt': re.compile(r'HP:\s*\d+\s*/\s*\d+.*MP:\s*\d+\s*/\s*\d+', re.I),
        
        # Game info patterns
        'exits': re.compile(r'(?:obvious exits?|exits?)[:\s]+([^\n]+)', re.I),
        'health': re.compile(r'(?:HP|Health)[:\s]*(\d+)/(\d+)', re.I),
        'mana': re.compile(r'(?:MP|Mana)[:\s]*(\d+)/(\d+)', re.I),
        'gold': re.compile(r'(?:Gold|Credits)[:\s]*(\d+)', re.I),
        'level': re.compile(r'Level[:\s]*(\d+)', re.I),
        
        # Combat patterns
        'attack_you': re.compile(r'(\w+) (?:attacks?|hits?|strikes?) you', re.I),
        'you_attack': re.compile(r'you (?:attack|hit|strike) (\w+)', re.I),
        'target_dies': re.compile(r'(\w+) (?:is dead|dies|has been slain)', re.I),
        'you_die': re.compile(r'you (?:have died|die|are dead)', re.I),
        
        # Social patterns
        'player_says': re.compile(r'(\w+) says?[,:\s]+["\']?(.+?)["\']?\s*$', re.I),
        'player_tells': re.compile(r'(\w+) tells? you[,:\s]+["\']?(.+?)["\']?\s*$', re.I),
        'player_yells': re.compile(r'(\w+) yells?[,:\s]+["\']?(.+?)["\']?\s*$', re.I),
        'also_here': re.compile(r'(?:also here|you see)[:\s]+([^\n]+)', re.I),
    }
    
    def __init__(self, state: GameState, config: BotConfig):
        self.state = state
        self.config = config
        self.logger = logging.getLogger("parser")
    
    def parse(self, raw: str) -> None:
        """Parse raw game output and update state."""
        text = ANSIProcessor.strip(raw)
        self.state.add_message(text)
        
        # Check login flow
        self._check_login_prompts(text)
        
        # Only parse game info if in-game
        if self.state.connection == ConnectionState.IN_GAME:
            self._parse_room_info(text)
            self._parse_character_info(text)
            self._parse_combat(text)
            self._parse_social(text)
    
    def _check_login_prompts(self, text: str) -> None:
        """Detect and handle login prompts."""
        patterns = self.PATTERNS

        # Once in-game, never reinterpret normal output as login prompts.
        if self.state.connection == ConnectionState.IN_GAME:
            return

        # This MUD has no 'welcome' string; entry is signaled by the status
        # prompt ([... HP:x/y MP:a/b ...]) or by GMCP Char/Room.Info blocks.
        if (patterns['welcome'].search(text)
                or patterns['game_prompt'].search(text)
                or '!!GMCP(Char' in text or '!!GMCP(Room.Info' in text):
            self.state.connection = ConnectionState.IN_GAME
            self.state.character.name = self.config.character_name
            self.logger.info("Successfully entered game")
            return
        
        # A stale session ("User is already connected. Kick them? [y/n]:") must be
        # answered 'y' before login proceeds; otherwise we'd re-send the password
        # and get 'invalid response' forever. Check this before the other prompts.
        if patterns['kick_prompt'].search(text):
            self.state.connection = ConnectionState.AWAITING_KICK
        elif patterns['username_prompt'].search(text):
            self.state.connection = ConnectionState.AWAITING_USERNAME
        elif patterns['new_password'].search(text):
            self.state.connection = ConnectionState.AWAITING_NEW_PASSWORD
        elif patterns['confirm_password'].search(text):
            self.state.connection = ConnectionState.AWAITING_CONFIRM_PASSWORD
        elif patterns['password_prompt'].search(text):
            self.state.connection = ConnectionState.AWAITING_PASSWORD
        elif patterns['character_name'].search(text):
            self.state.connection = ConnectionState.AWAITING_CHARACTER_NAME
        elif patterns['choose_race'].search(text):
            self.state.connection = ConnectionState.AWAITING_RACE
        elif patterns['choose_class'].search(text):
            self.state.connection = ConnectionState.AWAITING_CLASS
        elif patterns['press_enter'].search(text):
            self.state.connection = ConnectionState.AWAITING_CONFIRMATION
    
    def _parse_room_info(self, text: str) -> None:
        """Extract room information."""
        if match := self.PATTERNS['exits'].search(text):
            exits_str = match.group(1).lower()
            self.state.room.exits = [
                e.strip() for e in re.split(r'[,\s]+', exits_str)
                if e.strip() and e.strip() not in ('none', 'and')
            ]
        
        if match := self.PATTERNS['also_here'].search(text):
            names = re.findall(r'\b([A-Z][a-z]+)\b', match.group(1))
            for name in names:
                if name not in self.state.room.players:
                    self.state.room.players.append(name)
    
    def _parse_character_info(self, text: str) -> None:
        """Extract character stats."""
        char = self.state.character
        
        if match := self.PATTERNS['health'].search(text):
            char.health = int(match.group(1))
            char.health_max = int(match.group(2))
        
        if match := self.PATTERNS['mana'].search(text):
            char.mana = int(match.group(1))
            char.mana_max = int(match.group(2))
        
        if match := self.PATTERNS['gold'].search(text):
            char.gold = int(match.group(1))
        
        if match := self.PATTERNS['level'].search(text):
            char.level = int(match.group(1))
    
    def _parse_combat(self, text: str) -> None:
        """Track combat state."""
        char = self.state.character
        
        if match := self.PATTERNS['attack_you'].search(text):
            char.in_combat = True
            char.combat_target = match.group(1)
        
        if match := self.PATTERNS['you_attack'].search(text):
            char.in_combat = True
            char.combat_target = match.group(1)
        
        if self.PATTERNS['target_dies'].search(text) or self.PATTERNS['you_die'].search(text):
            char.in_combat = False
            char.combat_target = ""
    
    def _parse_social(self, text: str) -> None:
        """Track social interactions."""
        for pattern_name in ('player_says', 'player_tells', 'player_yells'):
            if match := self.PATTERNS[pattern_name].search(text):
                speaker = match.group(1)
                if speaker not in self.state.room.players:
                    self.state.room.players.append(speaker)


