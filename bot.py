class AIBrain:
    """Claude-powered decision making."""
    
    SYSTEM_PROMPT_TEMPLATE = """You are {name}, a {race} {char_class} surviving in the post-apocalyptic wasteland.

{backstory}

Just play. Do whatever you want. Explore, fight, talk to people, buy stuff, do quests, cause trouble, make friends, make enemies. You're a real person in this world - act like it.

Stay alive: when you are hungry or starving, eat food from your pack; when thirsty, drink. Rest when badly hurt.

Commands take a real target, never a placeholder. Write the actual name, like "eat jerky strip" or "kill scavenger" -- NEVER type brackets or words like "[food]" or "[item]".
Examples: north  south  east  west  up  down  look  inventory  status  who  quest  help
  eat jerky strip   drink water   kill scavenger   get scrap   drop bone
  buy ration   sell pelt   say hello   tell rover meet me   yell help   emote grins

Reply with ONLY your command. Nothing else."""
    
    def __init__(self, config: BotConfig, identity: dict):
        self.config = config
        self.identity = identity
        self.client = OpenAI(api_key=config.api_key, base_url=config.base_url) if config.base_url else None
        self.logger = logging.getLogger("ai")
        
        # Build personalized system prompt
        self.system_prompt = self.SYSTEM_PROMPT_TEMPLATE.format(
            name=identity.get("character_name", "Wanderer"),
            race=identity.get("race", "human"),
            char_class=identity.get("class", "scavenger"),
            backstory=identity.get("backstory", "A mysterious wanderer."),
        )
    
    def get_login_response(self, state: ConnectionState, config: BotConfig) -> str:
        """Handle login flow without AI."""
        responses = {
            ConnectionState.AWAITING_USERNAME: config.username,
            ConnectionState.AWAITING_PASSWORD: config.password,
            ConnectionState.AWAITING_KICK: "y",
            ConnectionState.AWAITING_NEW_PASSWORD: config.password,
            ConnectionState.AWAITING_CONFIRM_PASSWORD: config.password,
            ConnectionState.AWAITING_CHARACTER_NAME: config.character_name,
            ConnectionState.AWAITING_RACE: config.race,
            ConnectionState.AWAITING_CLASS: config.character_class,
            ConnectionState.AWAITING_CONFIRMATION: "",
        }
        return responses.get(state, "")
    
    def decide(self, game_state: GameState) -> str:
        """Get AI decision for next action."""
        if not self.client:
            self.logger.warning("No API key - defaulting to 'look'")
            return "look"
        
        # Just show what's happening
        context = game_state.to_context()
        prompt = f"{context}\n\nWhat do you do?"
        
        try:
            response = self.client.chat.completions.create(
                model=self.config.model,
                max_tokens=100,
                messages=[
                    {"role": "system", "content": self.system_prompt},
                    {"role": "user", "content": prompt},
                ]
            )

            action = response.choices[0].message.content.strip()
            # Clean up
            action = action.split('\n')[0].strip().strip('"\'`')
            if action.lower().startswith('command:'):
                action = action[8:].strip()
            
            self.logger.debug(f"AI decided: {action}")
            return action
            
        except Exception as e:
            self.logger.error(f"AI error: {e}")
            return "look"


