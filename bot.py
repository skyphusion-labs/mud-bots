class IdentityGenerator:
    """Generates and persists bot identity using AI."""
    
    # Available races in the game (subset - AI can pick from these)
    RACES = [
        "human", "mutant", "ghoul", "android", "cyborg", "wasteling",
        "dust elf", "sand goblin", "chrome junkie", "rad ghost",
        "salt born", "dust devil", "neon wraith", "bloodkin", "glasskin"
    ]
    
    # Available classes
    CLASSES = [
        "scavenger", "raider", "nomad", "wastelander", "drifter",
        "ruin diver", "scrap weaver", "heatweaver", "chrome hunter",
        "fixer", "gridbound"
    ]
    
    def __init__(self, config: BotConfig):
        self.config = config
        self.identity_file = Path(config.identity_file)
        self.client = OpenAI(api_key=config.api_key, base_url=config.base_url) if config.base_url else None
        self.logger = logging.getLogger("identity")
    
    def load_or_create(self) -> dict:
        """Load existing identity or create a new one."""
        # Try to load existing
        if self.identity_file.exists():
            try:
                with open(self.identity_file) as f:
                    identity = json.load(f)
                self.logger.info(f"Loaded identity: {identity['character_name']}")
                return identity
            except Exception as e:
                self.logger.warning(f"Could not load identity: {e}")
        
        # Generate new identity
        identity = self._generate_identity()
        
        # Save for persistence
        self._save_identity(identity)
        
        return identity
    
    def _generate_identity(self) -> dict:
        """Use AI to generate a unique character identity."""
        # Generate base username (needs to be unique for the account)
        random_suffix = ''.join(random.choices(string.ascii_lowercase + string.digits, k=6))
        username = f"ai_{random_suffix}"
        
        # Generate password
        password = ''.join(random.choices(string.ascii_letters + string.digits + "!@#$", k=16))
        
        if not self.client:
            # No API - use random defaults
            character_name = f"Wanderer{random.randint(100,999)}"
            race = random.choice(self.RACES)
            char_class = random.choice(self.CLASSES)
            backstory = "A mysterious wanderer of the wastes."
        else:
            # Use AI to create identity
            prompt = f"""You are creating a character for a post-apocalyptic MUD game called Packet Wastes.

Generate a unique, memorable character identity. Be creative and interesting.

Available races: {', '.join(self.RACES)}
Available classes: {', '.join(self.CLASSES)}

Respond in this exact JSON format (no other text):
{{
    "character_name": "A single name, 3-12 characters, no spaces, first letter capitalized",
    "race": "one of the available races exactly as written",
    "class": "one of the available classes exactly as written",
    "backstory": "2-3 sentences about who this character is and what drives them"
}}

Be creative! Make this character memorable and unique. The name should fit the post-apocalyptic wasteland setting."""

            try:
                response = self.client.chat.completions.create(
                    model=self.config.model,
                    max_tokens=300,
                    messages=[{"role": "user", "content": prompt}]
                )

                text = response.choices[0].message.content.strip()
                # Extract JSON from response
                json_match = re.search(r'\{[^}]+\}', text, re.DOTALL)
                if json_match:
                    data = json.loads(json_match.group())
                    character_name = data.get("character_name", f"Drifter{random.randint(100,999)}")
                    race = data.get("race", "human")
                    char_class = data.get("class", "scavenger")
                    backstory = data.get("backstory", "A wanderer of the wastes.")
                    
                    # Validate race and class
                    if race.lower() not in [r.lower() for r in self.RACES]:
                        race = random.choice(self.RACES)
                    if char_class.lower() not in [c.lower() for c in self.CLASSES]:
                        char_class = random.choice(self.CLASSES)
                else:
                    raise ValueError("No JSON in response")
                    
            except Exception as e:
                self.logger.warning(f"AI identity generation failed: {e}")
                character_name = f"Drifter{random.randint(100,999)}"
                race = random.choice(self.RACES)
                char_class = random.choice(self.CLASSES)
                backstory = "A mysterious wanderer of the wastes."
        
        # Clean up character name
        character_name = re.sub(r'[^a-zA-Z]', '', character_name)[:12]
        if character_name:
            character_name = character_name[0].upper() + character_name[1:].lower()
        else:
            character_name = f"Wanderer{random.randint(100,999)}"
        
        identity = {
            "username": username,
            "password": password,
            "character_name": character_name,
            "race": race.lower(),
            "class": char_class.lower(),
            "backstory": backstory,
            "created": datetime.now().isoformat(),
        }
        
        self.logger.info(f"Generated new identity: {character_name} the {race} {char_class}")
        self.logger.info(f"Backstory: {backstory}")
        
        return identity
    
    def _save_identity(self, identity: dict) -> None:
        """Save identity to file."""
        try:
            with open(self.identity_file, "w") as f:
                json.dump(identity, f, indent=2)
            self.logger.info(f"Saved identity to {self.identity_file}")
        except Exception as e:
            self.logger.error(f"Could not save identity: {e}")


