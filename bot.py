class ConnectionState(Enum):
    """Connection state machine."""
    DISCONNECTED = auto()
    CONNECTING = auto()
    AWAITING_USERNAME = auto()
    AWAITING_PASSWORD = auto()
    AWAITING_KICK = auto()
    AWAITING_NEW_PASSWORD = auto()
    AWAITING_CONFIRM_PASSWORD = auto()
    AWAITING_CHARACTER_NAME = auto()
    AWAITING_RACE = auto()
    AWAITING_CLASS = auto()
    AWAITING_CONFIRMATION = auto()
    IN_GAME = auto()


@dataclass 
class RoomState:
    """Current room information."""
    name: str = ""
    description: str = ""
    exits: list[str] = field(default_factory=list)
    players: list[str] = field(default_factory=list)
    mobs: list[str] = field(default_factory=list)
    items: list[str] = field(default_factory=list)


@dataclass
class CharacterState:
    """Character stats and status."""
    name: str = ""
    level: int = 1
    health: int = 100
    health_max: int = 100
    mana: int = 100
    mana_max: int = 100
    gold: int = 0
    experience: int = 0
    in_combat: bool = False
    combat_target: str = ""
    inventory: list[str] = field(default_factory=list)
    edibles: list[str] = field(default_factory=list)  # food names currently carried
    equipped: dict[str, str] = field(default_factory=dict)


@dataclass
class GameState:
    """Complete game state."""
    connection: ConnectionState = ConnectionState.DISCONNECTED
    room: RoomState = field(default_factory=RoomState)
    character: CharacterState = field(default_factory=CharacterState)
    message_buffer: list[str] = field(default_factory=list)
    last_command: str = ""
    last_command_time: float = 0.0
    
    def add_message(self, msg: str) -> None:
        """Add message lines to buffer (last 100), dropping GMCP/protocol noise."""
        clean = ANSIProcessor.strip(msg)
        for line in clean.splitlines():
            s = line.strip()
            if not s or s.startswith(('!!GMCP(', '!!MUSIC', 'TEXTMASK')):
                continue
            self.message_buffer.append(s)
        self.message_buffer = self.message_buffer[-100:]
    
    def recent_messages(self, n: int = 20) -> list[str]:
        """Get last n messages."""
        return self.message_buffer[-n:]
    
    def to_context(self) -> str:
        """Generate context string for AI."""
        room = self.room
        char = self.character
        
        return f"""=== CURRENT SITUATION ===
Location: {room.name or 'Unknown'}
{room.description[:300] if room.description else 'No description'}

Exits: {', '.join(room.exits) if room.exits else 'Look around to see exits'}
Players here: {', '.join(room.players) if room.players else 'None visible'}
Creatures here: {', '.join(room.mobs) if room.mobs else 'None visible'}
Items here: {', '.join(room.items) if room.items else 'None visible'}

=== YOUR STATUS ===
Health: {char.health}/{char.health_max} | Mana: {char.mana}/{char.mana_max}
Level: {char.level} | Gold: {char.gold}
Combat: {'Fighting ' + char.combat_target if char.in_combat else 'Not in combat'}
Food in your pack: {', '.join(char.edibles) if char.edibles else 'none'} (to eat, type the exact name, e.g. "eat {char.edibles[0] if char.edibles else 'ration'}")

=== RECENT EVENTS ===
{chr(10).join(self.recent_messages(15))}

=== LAST COMMAND ===
{self.last_command or 'None'}"""


