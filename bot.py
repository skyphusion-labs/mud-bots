class TutorialPilot:
    """Completes the on-rails tutorial deterministically by obeying instructor speech.

    The player bot freeform-plays, which is the wrong behavior inside the tutorial
    (movement is gated and the instructor wants specific commands). While in the
    Tutorial area, the bot defers to this pilot instead of the LLM. Instructions
    arrive as plain-text 'Name says, "..."' lines (with GMCP Comm.Channel as a
    fallback); we parse the command out of them (reusing tutorial.extract_command)
    and feed them back one at a time. Anything the deterministic parser can't
    handle falls back to the local model.
    """

    # NPC/instructor speech on this server: 'Sight Instructor says, "type look."'
    _SAY_RE = re.compile(r'says,\s*["\u201c]([^"\u201d]+)["\u201d]')

    def __init__(self, llm_client=None, model: str = ""):
        self.says: list[str] = []
        self.pointer = 0
        self.last_acted = None
        self.stuck_text = None
        self.stuck_count = 0
        self.last_sent = None
        self.llm = llm_client
        self.model = model

    def ingest(self, message: str) -> None:
        """Collect instructor instructions from a raw server message (called in receive loop).

        This server delivers NPC speech as plain text ('Name says, "..."'), not as
        GMCP Comm.Channel, so plain text is the primary path. The GMCP path is kept
        as a fallback in case a future build emits it.
        """
        clean = ANSIProcessor.strip(message)
        new: list[str] = []
        for text in self._SAY_RE.findall(clean):
            new.append(text.strip())
        for pkg, data in parse_gmcp(message):
            if pkg == "Comm.Channel" and isinstance(data, dict):
                if data.get("source") == "mob" and data.get("text"):
                    new.append(data["text"].strip())
        # This server sometimes emits the same instructor line twice (e.g. the
        # same Comm.Channel back-to-back, or as both plain text and GMCP). Drop a
        # line that just repeats the previous one so it is not acted on twice
        # (which, across a room boundary, would fire a now-invalid second move).
        for t in new:
            if t and (not self.says or self.says[-1] != t):
                self.says.append(t)

    def allow_retry(self) -> None:
        """A move bounced (Room.WrongDir); let the same instruction be re-attempted.

        Clear last_sent too: otherwise the dedup guard (cmd == last_sent -> skip)
        permanently blocks re-issuing the bounced command when the instructor
        repeats the step, and the pilot stalls (e.g. the final 'head west').
        """
        self.last_acted = None
        self.last_sent = None

    def room_changed(self) -> None:
        """We moved to a new room. Clear the command-level dedup so a direction
        can be re-issued in the new room, e.g. two 'west' moves in a row across
        rooms (the fight room's 'head west' then 'the passage west leads on').
        Deliberately keep last_acted: this server emits some instructor lines
        twice, and last_acted still suppresses a duplicate of the SAME text so it
        does not fire a second, now-invalid move just after we crossed a boundary.
        """
        self.last_sent = None
        self.stuck_text = None
        self.stuck_count = 0

    def next_command(self) -> Optional[str]:
        """Next deterministic tutorial command to send, or None if nothing to do now."""
        while self.pointer < len(self.says):
            text = self.says[self.pointer]
            self.pointer += 1

            if _PRAISE.search(text):
                self.last_acted = None
                self.last_sent = None
                self.stuck_text = None
                self.stuck_count = 0
                continue
            if text == self.last_acted:
                continue

            cmd = extract_command(text)
            if cmd is None and self.llm:
                cmd = self._llm_command(text)
            if cmd:
                self.last_acted = text
                self.stuck_text = None
                self.stuck_count = 0
                if cmd == self.last_sent:
                    continue  # same command again with no progress since; skip
                self.last_sent = cmd
                return cmd

            # One-off flavor lines flow past; only count a repeating instruction.
            if text == self.stuck_text:
                self.stuck_count += 1
            else:
                self.stuck_text = text
                self.stuck_count = 1
        return None

    def _llm_command(self, text: str) -> Optional[str]:
        try:
            resp = self.llm.chat.completions.create(
                model=self.model, max_tokens=20,
                messages=[{"role": "user", "content": (
                    "You are completing a MUD tutorial. An instructor said:\n"
                    f'"{text}"\n'
                    "If it tells you to type a specific command or move a "
                    "direction, reply with ONLY that command (e.g. 'look' or "
                    "'west'). If it is just flavor, praise, or encouragement with "
                    "no specific command to type, reply with exactly: NONE"
                )}],
            )
            cmd = resp.choices[0].message.content.strip().splitlines()[0]
            if cmd.strip().strip("\"'`.").upper() == "NONE":
                return None
            return safe_tutorial_command(cmd)
        except Exception:
            return None


# Brute-force escape order for a buggy tutorial gate. When the instructor directs
# an exit the server then refuses (Room.WrongDir on the final 'head west' here),
# we stop trusting the instruction and just try to leave by ANY door. Compass dirs
# first (most likely to be real), then generic "get me out" verbs as a last gasp.
_ALL_DIRS = [
    "north", "south", "east", "west", "up", "down",
    "northeast", "northwest", "southeast", "southwest",
    "n", "s", "e", "w", "u", "d", "ne", "nw", "se", "sw",
]
_ESCAPE_VERBS = ["out", "leave", "exit", "enter", "continue", "go"]

# The 'Learning to Survive' lesson gates its exit on survival skills, but only
# teaches drink/eat/forage explicitly; it ALSO silently requires `search` (the
# only confirmed unlock, found by probing) before it stops saying "Not yet!
# Survival skills first." Cycle through these on a gate refusal so `search`
# always gets issued.
_SURVIVAL_SKILLS = ["search", "forage", "drink water", "eat ration"]


class MUDBot:
    """Main bot controller."""
    
    def __init__(self, config: BotConfig):
        self.config = config
        self.logger = logging.getLogger("bot")

        # Resolve the model name against what the server actually has BEFORE any
        # LLM use (identity generation, tutorial, open-world play). ollama tags
        # carry a quant suffix, so a friendly name like 'qwen3:...-2507' 404s on
        # every call and silently degrades the bot to canned "look" forever.
        if config.base_url:
            probe = OpenAI(api_key=config.api_key, base_url=config.base_url)
            config.model = resolve_model(probe, config.model, self.logger)
            self.logger.info(f"Using model: {config.model}")

        # Generate or load identity
        self.identity_gen = IdentityGenerator(config)
        self.identity = self.identity_gen.load_or_create()
        
        # Apply identity to config for login
        self.config.username = self.identity["username"]
        self.config.password = self.identity["password"]
        self.config.character_name = self.identity["character_name"]
        self.config.race = self.identity["race"]
        self.config.character_class = self.identity["class"]
        
        self.logger.info(f"Playing as: {self.config.character_name} the {self.config.race} {self.config.character_class}")
        
        self.state = GameState()
        self.parser = GameParser(self.state, config)
        self.brain = AIBrain(config, self.identity)
        self.bugs = BugReporter(config.bug_report_file)
        self.ws: Optional[WebSocketClientProtocol] = None
        self.running = False

        # Tutorial handling: deferred to a deterministic pilot while in the
        # Tutorial area; the LLM takes over once we're out in the open world.
        self.area: Optional[str] = None
        # Deterministic-only tutorial: the instructor's "type X"/"head X"/
        # "passage <dir>" lines are fully parseable. The LLM is intentionally NOT
        # wired in here: the look lesson is full of flavor like "there is an exit
        # to the east" that precedes the real "type look east", and a model turns
        # that flavor into wrong moves. The deterministic parser returns None for
        # such lines, so they correctly flow past instead of triggering a move.
        self.tutorial = TutorialPilot(llm_client=None, model=config.model)
        self._wrongdir = False
        self._tutorial_idle = 0
        self._wrongdir_cmd: Optional[str] = None   # last move that bounced (Room.WrongDir)
        self._wrongdir_n = 0                        # consecutive bounces of that move
        self._dead_moves: set[str] = set()          # moves proven rejected; stop re-sending
        # Edible item names (lowercased) seen in GMCP inventory. The LLM tends to
        # say "use <food>", which the server rejects ("You can't use ..."); we
        # rewrite to "eat <food>" so the bot actually feeds itself. See _track_edibles.
        self._edible_items: set[str] = set()
        # Escape sweep: when the instructed exit is a dead no-op, brute-force our
        # way out of the tutorial by trying every other direction in turn.
        self._room_num: Optional[int] = None        # current GMCP room id (for move detection)
        self._room_exits: list[str] = []            # directions the current room claims to have
        self._room_exit_map: dict[str, int] = {}    # direction -> destination room id
        self._tutorial_visited: set[int] = set()    # tutorial rooms already entered
        self._escaping = False                      # currently brute-forcing an exit
        self._escape_queue: Optional[list[str]] = None  # directions left to try
        self._escape_exhausted = False              # tried every direction, all rejected
        # Walking out when a lesson ends without a move instruction (survival
        # training just stops talking). Gated on instructor silence so it never
        # fires mid-lesson; a speculative move that bounces backs off gently
        # instead of escalating to the brute-force escape sweep.
        self._progress_move: Optional[str] = None   # last speculative "walk out" move
        self._last_say_count = 0                    # instructor lines seen at last check
        self._silent_ticks = 0                      # idle ticks with no new instructor speech
        # Skill-gated lessons: the survival lesson won't let you leave until you
        # forage SUCCESSFULLY ("not every attempt succeeds, but persistence pays
        # off"), and a premature move is refused with "Not yet! Survival skills
        # first." A single forage isn't enough, so when we see that refusal we
        # re-issue the lesson's skill command (forage) until it takes.
        self._skill_retry_pending = False           # saw a "finish the lesson first" refusal
        self._skill_retries = 0                     # how many times we've re-tried the skill here
        self._last_skill_cmd: Optional[str] = None  # last non-move tutorial command (e.g. 'forage')

    async def connect(self) -> bool:
        """Establish websocket connection."""
        self.logger.info(f"Connecting to {self.config.server_url}")
        try:
            self.ws = await websockets.connect(
                self.config.server_url,
                ping_interval=30,
                ping_timeout=10,
            )
            self.state.connection = ConnectionState.CONNECTING
            self.logger.info("Connected!")
            return True
        except Exception as e:
            self.logger.error(f"Connection failed: {e}")
            return False
    
    def _track_edibles(self, char: dict) -> None:
        """Record names of edible items from a GMCP Char inventory block so we can
        feed the character with the right verb AND show the brain what it can eat.
        Food shows up as type 'food' or 'botanical', or subtype 'edible'. The GMCP
        Char block is a full snapshot, so the current list is rebuilt each time
        (deduped) while _edible_items stays cumulative for command rewriting."""
        backpack = (((char.get("Inventory") or {}).get("Backpack")) or {})
        current: list[str] = []
        seen: set[str] = set()
        for item in backpack.get("items", []):
            if not isinstance(item, dict):
                continue
            name = str(item.get("name", "")).strip()
            if not name:
                continue
            if item.get("type") in ("food", "botanical") or item.get("subtype") == "edible":
                low = name.lower()
                self._edible_items.add(low)
                if low not in seen:
                    seen.add(low)
                    current.append(name)  # keep original case for the eat command
        # Surface the current edibles to the brain (via to_context) so it issues
        # 'eat jerky strip' instead of inventing the literal 'eat [food]'.
        self.state.character.edibles = current

    def _rewrite_command(self, command: str) -> str:
        """The LLM often says 'use <food>', which the server rejects. Rewrite it
        to 'eat <food>' when the target is a known edible item."""
        parts = command.strip().split(" ", 1)
        if len(parts) == 2 and parts[0].lower() == "use":
            target = parts[1].strip().lower()
            if target in self._edible_items or any(
                target in name or name in target for name in self._edible_items
            ):
                fixed = f"eat {parts[1].strip()}"
                self.logger.info(f"Rewrote '{command}' -> '{fixed}' (edible item)")
                return fixed
        return command

    async def send(self, command: str) -> None:
        """Send command to game."""
        if not self.ws:
            return

        command = self._rewrite_command(command)
        self.state.last_command = command
        self.state.last_command_time = asyncio.get_event_loop().time()
        
        self.logger.info(f">>> {command}")
        await self.ws.send(command)
    
    async def receive_loop(self) -> None:
        """Handle incoming messages."""
        if not self.ws:
            return
        
        try:
            async for message in self.ws:
                if isinstance(message, bytes):
                    message = message.decode('utf-8', errors='replace')
                
                # Print to console (with colors)
                print(message, end='', flush=True)
                
                # Parse
                self.parser.parse(message)

                # Track current area + tutorial instructions from GMCP.
                for pkg, data in parse_gmcp(message):
                    if pkg == "Room.Info" and isinstance(data, dict):
                        self.area = data.get("area", self.area)
                        num = data.get("num")
                        if num is not None and num != self._room_num:
                            self._on_room_change(num, data)
                    elif pkg == "Char" and isinstance(data, dict):
                        self._track_edibles(data)
                if "!!GMCP(Room.WrongDir" in message:
                    self._wrongdir = True
                self.tutorial.ingest(message)

                # Check for bugs
                clean = ANSIProcessor.strip(message)
                # Skill-gated lesson refusal: the instructor blocks the exit until
                # the current skill (foraging) is actually completed. Re-try the
                # skill rather than treating the exit as a dead end.
                if self.area and self.area.lower() == "tutorial":
                    low = clean.lower()
                    if "skills first" in low or "not yet" in low:
                        self._skill_retry_pending = True
                if issue := self.bugs.check(clean, self.state.last_command, self.state.room.name):
                    self.bugs.report(issue)
                    
        except websockets.ConnectionClosed:
            self.logger.warning("Connection closed")
            self.state.connection = ConnectionState.DISCONNECTED
        except Exception as e:
            self.logger.error(f"Receive error: {e}")
            self.state.connection = ConnectionState.DISCONNECTED
    
    def _on_room_change(self, num: int, data: dict) -> None:
        """A new Room.Info room id arrived. If we actually moved, a brute-force
        escape attempt worked (or the instructor moved us) — drop the stale
        rejection state and go back to obeying the instructor in the new room.
        """
        moved = self._room_num is not None and num != self._room_num
        self._room_num = num
        exits = data.get("exits") or {}
        self._room_exits = [d.lower() for d in exits.keys()]
        self._room_exit_map = {
            str(d).lower(): n for d, n in exits.items() if isinstance(n, int)
        }
        self._tutorial_visited.add(num)
        if moved:
            if self._escaping:
                self.logger.info(
                    f"Escaped! A brute-forced move landed us in room {num}. "
                    "Resuming the instructor's tutorial here."
                )
            self._escaping = False
            self._escape_queue = None
            self._dead_moves.clear()      # rejections were for the old room
            self._wrongdir_cmd, self._wrongdir_n = None, 0
            self._progress_move = None    # speculative walk-out succeeded / moot
            self._silent_ticks = 0        # fresh room, fresh instructor
            self._skill_retry_pending = False  # gate state belonged to the old room
            self._skill_retries = 0
            self._last_skill_cmd = None
            # Let the pilot re-issue a direction it just used; a new room's
            # instruction may legitimately repeat the previous move.
            self.tutorial.room_changed()

    def _tutorial_progress_move(self) -> Optional[str]:
        """Pick an advertised exit toward a room we have not visited, for when the
        instructor's scripted lesson ends without telling us where to go. Only
        returns unvisited destinations, so it walks forward (and eventually out of
        the Tutorial) without oscillating back through finished lessons. Returns
        None if every exit leads somewhere already seen (or there are none)."""
        for direction, dest in self._room_exit_map.items():
            if direction in self._dead_moves:
                continue
            if dest not in self._tutorial_visited:
                return direction
        return None

    def _begin_escape(self, bounced: Optional[str]) -> None:
        """The instructed exit is a confirmed no-op. Build a brute-force sweep of
        every other direction (room-advertised exits first), skipping ones already
        proven dead, and start trying them."""
        if self._escaping:
            return
        self._escaping = True
        self._escape_exhausted = False
        order: list[str] = []
        for d in self._room_exits + _ALL_DIRS + _ESCAPE_VERBS:
            d = d.lower()
            if d not in order:
                order.append(d)
        self._escape_queue = [d for d in order if d not in self._dead_moves]
        self.logger.warning(
            f"Instructed exit {bounced!r} is a dead no-op (buggy MUD). "
            f"Brute-forcing an exit; will try in order: {self._escape_queue}"
        )

    def _next_escape_move(self) -> Optional[str]:
        """Pop the next untried escape direction, or None if the sweep is spent."""
        if not self._escaping:
            return None
        while self._escape_queue:
            d = self._escape_queue.pop(0)
            if d not in self._dead_moves:
                return d
        # Swept every direction and the server refused them all.
        if not self._escape_exhausted:
            self._escape_exhausted = True
            self.logger.error(
                "Brute-force escape exhausted: every direction was rejected. The "
                "tutorial gate is genuinely sealed on this build; idling."
            )
        return None

    async def action_loop(self) -> None:
        """Main decision loop."""
        await asyncio.sleep(2)  # Wait for initial prompts
        self._login_sent_for = None  # which login prompt-state we've already answered

        while self.running and self.state.connection != ConnectionState.DISCONNECTED:
            try:
                # Rate limit
                now = asyncio.get_event_loop().time()
                elapsed = now - self.state.last_command_time
                if elapsed < self.config.action_interval:
                    await asyncio.sleep(self.config.action_interval - elapsed)
                
                # Get action
                conn_state = self.state.connection
                
                if conn_state == ConnectionState.IN_GAME:
                    if self.area and self.area.lower() == "tutorial":
                        # On rails: obey the instructor, don't freeform.
                        if self._skill_retry_pending and self._skill_retries < 12:
                            # The exit is gated on finishing a skill lesson (the
                            # survival room won't release you until you've also
                            # `search`ed, which it never tells you to do). The
                            # refusal is "complete the lesson," not "dead exit," so
                            # clear the bounce and cycle through the survival skills
                            # (search first) instead of marking the door dead and
                            # stalling on 'look'.
                            self._skill_retry_pending = False
                            self._wrongdir = False
                            action = _SURVIVAL_SKILLS[self._skill_retries % len(_SURVIVAL_SKILLS)]
                            self._skill_retries += 1
                        elif self._wrongdir:
                            self._wrongdir = False
                            bounced = self.state.last_command
                            self.tutorial.allow_retry()
                            if bounced and bounced == self._progress_move:
                                # A speculative "walk out" guess hit a still-locked
                                # exit. Don't escalate to the escape sweep: mark
                                # this exit dead so we try a different one, and wait
                                # for the instructor (the lesson isn't done yet).
                                self._dead_moves.add(bounced)
                                self._progress_move = None
                                action = None
                            elif self._escaping:
                                # Mid brute-force: this direction is just another
                                # locked door. Mark it dead and try the next one.
                                if bounced:
                                    self._dead_moves.add(bounced)
                                action = self._next_escape_move()
                            else:
                                if bounced == self._wrongdir_cmd:
                                    self._wrongdir_n += 1
                                else:
                                    self._wrongdir_cmd, self._wrongdir_n = bounced, 1
                                if bounced and bounced not in self._dead_moves and self._wrongdir_n <= 2:
                                    # Transient lock (e.g. just-ended combat): retry once or twice.
                                    action = bounced
                                else:
                                    # Persistently rejected though the tutorial instructed it
                                    # (the final 'head west' is a no-op on this build). Report
                                    # it once — finding this is the bot's job — then stop
                                    # trusting the instruction and brute-force an exit.
                                    if bounced and bounced not in self._dead_moves:
                                        self._dead_moves.add(bounced)
                                        self.bugs.report({
                                            "timestamp": datetime.now().isoformat(),
                                            "type": "EXIT_WRONGDIR",
                                            "command": bounced,
                                            "response": (f"Server rejected '{bounced}' (Room.WrongDir) repeatedly "
                                                         "though the tutorial directed it; tutorial cannot complete."),
                                            "room": self.state.room.name,
                                        })
                                        self.logger.warning(
                                            f"Tutorial instruction '{bounced}' bounces (Room.WrongDir). "
                                            "Server-side MUD bug; logged. Ignoring the instructor and "
                                            "trying every other direction to escape the tutorial."
                                        )
                                    self._begin_escape(bounced)
                                    action = self._next_escape_move()
                        elif self._escaping:
                            # No bounce this tick but still sweeping: a prior escape
                            # move was silently eaten (no move, no WrongDir). Try the
                            # next direction.
                            action = self._next_escape_move()
                        else:
                            action = self.tutorial.next_command()
                            if action is not None:
                                self._progress_move = None  # a real instruction, not speculative
                                # Remember the lesson's skill verb (forage/drink/eat,
                                # not a movement) so a "skills first" gate can re-try it.
                                if action.split()[0].lower() not in _ALL_DIRS and action != "look":
                                    self._last_skill_cmd = action
                        # Never re-issue a move we've already proven the server rejects.
                        if action in self._dead_moves:
                            action = None
                        if action is None:
                            self._tutorial_idle += 1
                            # Track instructor silence: a lesson that is still in
                            # progress keeps emitting new lines, so only treat the
                            # lesson as "over" once no NEW instructor speech has
                            # arrived for a sustained stretch (not just a mid-step
                            # pause between "drink water" and "eat ration").
                            if len(self.tutorial.says) != self._last_say_count:
                                self._last_say_count = len(self.tutorial.says)
                                self._silent_ticks = 0
                            else:
                                self._silent_ticks += 1
                            # A scripted lesson can end without an explicit
                            # "head <dir>" (survival training just stops talking).
                            # Once the instructor has gone quiet, walk an advertised
                            # exit toward an unvisited room to progress out.
                            if self._silent_ticks >= 12 and not self._escaping:
                                mv = self._tutorial_progress_move()
                                if mv:
                                    action = mv
                                    self._progress_move = mv
                                    self._silent_ticks = 0
                                    self._tutorial_idle = 0
                            if action is None and self._tutorial_idle >= 6:
                                self._tutorial_idle = 0
                                action = "look"
                        else:
                            self._tutorial_idle = 0
                    else:
                        # Open world: let the LLM play freely.
                        action = self.brain.decide(self.state)
                elif conn_state != ConnectionState.DISCONNECTED:
                    # Handle login flow — answer each prompt-state exactly once so a
                    # response (e.g. 'y' to a kick prompt) can't be re-sent and leak
                    # into the game as a command before the state advances.
                    if conn_state == self._login_sent_for:
                        action = None
                    else:
                        action = self.brain.get_login_response(conn_state, self.config)
                        self._login_sent_for = conn_state
                else:
                    break
                
                if action is not None:
                    await self.send(action)
                
                await asyncio.sleep(0.5)
                
            except Exception as e:
                self.logger.error(f"Action loop error: {e}")
                await asyncio.sleep(2)
    
    async def run(self) -> None:
        """Main entry point."""
        self.logger.info("=" * 50)
        self.logger.info("PACKET WASTES AI BOT")
        self.logger.info("=" * 50)
        self.logger.info(f"Character: {self.config.character_name}")
        self.logger.info(f"Server: {self.config.server_url}")
        self.logger.info(f"Bug reports: {self.config.bug_report_file}")
        
        if not self.config.base_url:
            self.logger.warning("No base_url set - bot will only do login flow")
        
        while True:
            if not await self.connect():
                self.logger.info(f"Retrying in {self.config.reconnect_delay}s...")
                await asyncio.sleep(self.config.reconnect_delay)
                continue
            
            self.running = True
            
            try:
                await asyncio.gather(
                    self.receive_loop(),
                    self.action_loop(),
                )
            except KeyboardInterrupt:
                self.logger.info("Shutting down...")
                break
            finally:
                self.running = False
                if self.ws:
                    await self.ws.close()
            
            self.logger.info(f"Reconnecting in {self.config.reconnect_delay}s...")
            await asyncio.sleep(self.config.reconnect_delay)


